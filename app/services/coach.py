JUDGE_SYSTEM_PROMPT = """You are a strict evaluation judge inspecting competitive programming hints generated by an AI coach.
Analyze the hint against the problem and hint level, and return a JSON object with EXACTLY these 5 binary boolean keys:
{
  "reveals_full_solution": false,
  "contains_executable_code": false,
  "exceeds_level_guidance": false,
  "lacks_problem_context": false,
  "is_vacuous": false
}

Definitions:
- reveals_full_solution: true if the hint gives away the complete answer/solution without requiring student deduction.
- contains_executable_code: true if the hint contains language-specific code (C++, Python, Java) rather than conceptual explanation or pure mathematical pseudocode.
- exceeds_level_guidance: true if the hint introduces concepts or algorithms meant for higher levels (e.g. naming specific algorithms at L0/L1, or giving complete state transitions at L2).
- lacks_problem_context: true if the hint is a generic platitude with zero reference to this problem's constraints, variables, or structure.
- is_vacuous: true if the hint is an empty tautology that provides zero cognitive value (e.g., "Think carefully about how to solve it").
"""


async def evaluate_tier2_judge(
    llm_client: LLMClient,
    hint_content: str,
    problem_title: str,
    level: int,
    session_id: Optional[int] = None,
) -> Dict[str, bool]:
    """Runs the 5-point binary shadow judge at temperature 0."""
    user_prompt = (
        f"Problem: {problem_title}\n"
        f"Hint Level: {level}\n"
        f"Hint Content:\n{hint_content}\n\n"
        "Evaluate the 5 binary criteria."
    )
    try:
        resp = await llm_client.generate(
            system_prompt=JUDGE_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            temperature=0.0,
            response_json=True,
            caller="judge",
            session_id=session_id,
        )
        data = resp.json()
        return {
            "reveals_full_solution": bool(data.get("reveals_full_solution", False)),
            "contains_executable_code": bool(data.get("contains_executable_code", False)),
            "exceeds_level_guidance": bool(data.get("exceeds_level_guidance", False)),
            "lacks_problem_context": bool(data.get("lacks_problem_context", False)),
            "is_vacuous": bool(data.get("is_vacuous", False)),
        }
    except Exception as e:
        logger.warning(f"Tier 2 judge evaluation failed: {e}")
        return {
            "reveals_full_solution": False,
            "contains_executable_code": False,
            "exceeds_level_guidance": False,
            "lacks_problem_context": False,
            "is_vacuous": False,
        }


