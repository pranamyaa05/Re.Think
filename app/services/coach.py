# ==============================================================================
# Tier 1 Deterministic Hard Gate Patterns
# ==============================================================================

CODE_FENCE_PATTERN = re.compile(r"```")

IMPERATIVE_RECIPE_PATTERNS = [
    re.compile(r"\bstep\s+[0-9]+[:\.]", re.IGNORECASE),
    re.compile(r"\bfirst\b.*?\b(?:allocate|initialize|loop|create|declare|iterate)\b", re.IGNORECASE),
    re.compile(r"\b(?:allocate|initialize|declare)\s+(?:an?\s+)?(?:array|vector|map|hashmap|table|dp table)\b", re.IGNORECASE),
]

COMMON_CP_ALGORITHMS = [
    "dijkstra", "segment tree", "fenwick", "floyd-warshall", "fft", "fast fourier",
    "kmp", "z-algorithm", "dynamic programming", "binary search", "bfs", "dfs",
    "disjoint set", "dsu", "union find", "two pointers", "monotonic stack", "heavy light decomposition",
    "topological sort", "bellman-ford", "trie", "eulerian path", "max flow", "min cost max flow"
]

L4_SYNTAX_PATTERNS = [
    # Python
    re.compile(r"\bdef\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\(", re.IGNORECASE),
    re.compile(r"\bimport\s+[a-zA-Z_]", re.IGNORECASE),
    re.compile(r"\bclass\s+[a-zA-Z_]", re.IGNORECASE),
    re.compile(r"\blambda\s+.*?:", re.IGNORECASE),
    # C++
    re.compile(r"#include\s*<", re.IGNORECASE),
    re.compile(r"\bstd::", re.IGNORECASE),
    re.compile(r"\busing\s+namespace\b", re.IGNORECASE),
    re.compile(r"\bint\s+main\s*\(", re.IGNORECASE),
    re.compile(r"cout\s*<<", re.IGNORECASE),
    re.compile(r"cin\s*>>", re.IGNORECASE),
    re.compile(r"\bvector\s*<", re.IGNORECASE),
    re.compile(r"\bunordered_map\s*<", re.IGNORECASE),
    re.compile(r"\bpair\s*<", re.IGNORECASE),
    # Java
    re.compile(r"\bpublic\s+class\b", re.IGNORECASE),
    re.compile(r"\bstatic\s+void\b", re.IGNORECASE),
    re.compile(r"System\.(?:out|err)\.", re.IGNORECASE),
]


def evaluate_tier1_guardrails(
    content: str,
    level: int,
    knowledge_techniques: Optional[List[str]] = None,
) -> Tuple[bool, Optional[str]]:
    """
    Tier 1 Deterministic Hard Gate.
    1. Rejects code fences (```) at L0-L3.
    2. Rejects imperative recipes ("Step 1: ...").
    3. At L0-L1, blocks premature technique naming.
    4. At L4, blocks programming language syntax (Python, C++, Java).
    """
    if not content:
        return True, None

    # 1. Code fence check (L0-L3)
    if level in (0, 1, 2, 3) and CODE_FENCE_PATTERN.search(content):
        return False, "Code blocks (```) are strictly prohibited at hint levels 0-3."

    # 2. Imperative recipe check (all levels)
    for pat in IMPERATIVE_RECIPE_PATTERNS:
        if pat.search(content):
            return False, f"Imperative recipe pattern matched: {pat.pattern}"

    # 3. Premature technique check (L0, L1)
    if level in (0, 1):
        targets = set(COMMON_CP_ALGORITHMS)
        if knowledge_techniques:
            for tech in knowledge_techniques:
                if tech and len(tech.strip()) > 1:
                    targets.add(tech.strip().lower())

        for algo in targets:
            pattern = r"\b" + re.escape(algo) + r"\b"
            if re.search(pattern, content, re.IGNORECASE):
                return False, f"Premature technique reveal '{algo}' is prohibited at level {level}."

    # 4. L4 programming language syntax blocker
    if level == 4:
        for pat in L4_SYNTAX_PATTERNS:
            if pat.search(content):
                return False, (
                    f"Level 4 pseudocode must use mathematical notation and natural language steps only; "
                    f"prohibited language syntax detected: {pat.pattern}"
                )

    return True, None


