class CoachService:
    def __init__(self, llm_client: Optional[LLMClient] = None):
        self.llm_client = llm_client or LLMClient()

    async def create_session(
        self,
        user_id: int,
        problem_id: int,
    ) -> HintSession:
        """
        Initializes a coaching session:
        1. Validates user and problem exist.
        2. Resolves coach_mode from ProblemKnowledge.
        3. Generates the initial Level 0 diagnostic question.
        4. Evaluates Tier 1 and Tier 2 guardrails.
        5. Persists session and initial coach message.
        """
        async with async_session_factory() as session:
            # Validate problem
            prob_res = await session.execute(select(Problem).where(Problem.id == problem_id))
            problem = prob_res.scalar_one_or_none()
            if not problem:
                raise ValueError(f"Problem id={problem_id} not found.")

            # Validate user
            user_res = await session.execute(select(User).where(User.id == user_id))
            user = user_res.scalar_one_or_none()
            if not user:
                raise ValueError(f"User id={user_id} not found.")

            # Fetch knowledge
            know_res = await session.execute(
                select(ProblemKnowledge).where(ProblemKnowledge.problem_id == problem_id)
            )
            knowledge = know_res.scalar_one_or_none()
            coach_mode = resolve_coach_mode(knowledge)

            # Create session entity
            hint_session = HintSession(
                user_id=user_id,
                problem_id=problem_id,
                current_level=0,
                coach_mode=coach_mode,
                knowledge_confidence=coach_mode,
                outcome="ongoing",
            )
            session.add(hint_session)
            await session.commit()  # Commit so hint_session exists in DB for FK in llm_call_log
            session_id = hint_session.id

            # Generate initial Level 0 hint
            hint_text, tier1_blocked = await generate_hint(
                llm_client=self.llm_client,
                target_level=0,
                coach_mode=coach_mode,
                problem=problem,
                knowledge=knowledge,
                dialog_history=[],
                user_message="I'm starting to look at this problem. Where should I begin?",
                session_id=session_id,
            )

            # Tier 2 shadow judge evaluation
            leakage_checklist = await evaluate_tier2_judge(
                llm_client=self.llm_client,
                hint_content=hint_text,
                problem_title=problem.title,
                level=0,
                session_id=session_id,
            )

            # Record initial coach message
            msg = HintMessage(
                session_id=session_id,
                role="coach",
                hint_level=0,
                content=hint_text,
                tier1_blocked=tier1_blocked,
                leakage_checklist=leakage_checklist,
            )
            session.add(msg)
            await session.commit()

            # Reload session with messages
            res = await session.execute(
                select(HintSession)
                .options(selectinload(HintSession.messages), selectinload(HintSession.problem))
                .where(HintSession.id == session_id)
            )
            return res.scalar_one()

    async def process_user_message(
        self,
        session_id: int,
        user_message: str,
        current_code: Optional[str] = None,
        request_escalation: bool = False,
    ) -> Tuple[HintMessage, HintSession]:
        """
        Executes a turn in the coaching dialog:
        1. Persists user message with optional code snapshot.
        2. Runs FSM Evaluator to assess progress and select next level.
        3. Runs Hint Generator for the target level.
        4. Runs Tier 1 guardrails and Tier 2 shadow judge.
        5. Persists coach message and updates session.
        """
        async with async_session_factory() as session:
            # Load session with messages and problem
            res = await session.execute(
                select(HintSession)
                .options(selectinload(HintSession.messages), selectinload(HintSession.problem))
                .where(HintSession.id == session_id)
            )
            hint_session = res.scalar_one_or_none()
            if not hint_session:
                raise ValueError(f"HintSession id={session_id} not found.")

            if hint_session.outcome != "ongoing":
                raise ValueError(f"HintSession id={session_id} is concluded ({hint_session.outcome}).")

            problem = hint_session.problem

            # Fetch knowledge
            know_res = await session.execute(
                select(ProblemKnowledge).where(ProblemKnowledge.problem_id == problem.id)
            )
            knowledge = know_res.scalar_one_or_none()

            # Record user message
            user_msg = HintMessage(
                session_id=session_id,
                role="user",
                hint_level=None,
                content=user_message,
                code_snapshot=current_code,
            )
            session.add(user_msg)
            await session.flush()

            # Build dialog history
            history = [
                {"role": m.role, "content": m.content}
                for m in hint_session.messages
            ]

            # 1. FSM Evaluator step
            fsm_eval = await evaluate_fsm_transition(
                llm_client=self.llm_client,
                problem_title=problem.title,
                current_level=hint_session.current_level,
                user_message=user_message,
                current_code=current_code,
                previous_messages=history,
                user_stated_approach=hint_session.user_stated_approach,
                request_escalation=request_escalation,
                session_id=session_id,
            )

            understood = fsm_eval.get("understood_current_level", True)
            target_level = min(4, max(0, fsm_eval.get("recommended_next_level", hint_session.current_level)))
            extracted_approach = fsm_eval.get("extracted_approach")

            if extracted_approach:
                hint_session.user_stated_approach = extracted_approach
            hint_session.current_level = target_level
            hint_session.last_activity_at = datetime.now(timezone.utc)

            # 2. Hint Generator step
            is_hold = not understood
            hint_text, tier1_blocked = await generate_hint(
                llm_client=self.llm_client,
                target_level=target_level,
                coach_mode=hint_session.coach_mode,
                problem=problem,
                knowledge=knowledge,
                dialog_history=history,
                user_message=user_message,
                current_code=current_code,
                fsm_evaluation=fsm_eval,
                is_hold=is_hold,
                session_id=session_id,
            )

            # 3. Tier 2 shadow judge evaluation
            leakage_checklist = await evaluate_tier2_judge(
                llm_client=self.llm_client,
                hint_content=hint_text,
                problem_title=problem.title,
                level=target_level,
                session_id=session_id,
            )

            # 4. Record coach message
            coach_msg = HintMessage(
                session_id=session_id,
                role="coach",
                hint_level=target_level,
                content=hint_text,
                tier1_blocked=tier1_blocked,
                leakage_checklist=leakage_checklist,
            )
            session.add(coach_msg)
            await session.commit()

            # Reload updated session
            res = await session.execute(
                select(HintSession)
                .options(selectinload(HintSession.messages), selectinload(HintSession.problem))
                .where(HintSession.id == session_id)
            )
            updated_session = res.scalar_one()

            # Fetch committed coach msg
            coach_msg_res = await session.execute(
                select(HintMessage).where(HintMessage.id == coach_msg.id)
            )
            saved_coach_msg = coach_msg_res.scalar_one()

            return saved_coach_msg, updated_session

    async def conclude_session(
        self,
        session_id: int,
        outcome: str,
    ) -> HintSession:
        """Concludes a session with 'solved' or 'gave_up'."""
        if outcome not in ("solved", "gave_up"):
            raise ValueError(f"Invalid outcome '{outcome}'. Must be 'solved' or 'gave_up'.")

        async with async_session_factory() as session:
            res = await session.execute(
                select(HintSession)
                .options(selectinload(HintSession.messages), selectinload(HintSession.problem))
                .where(HintSession.id == session_id)
            )
            hint_session = res.scalar_one_or_none()
            if not hint_session:
                raise ValueError(f"HintSession id={session_id} not found.")

            hint_session.outcome = outcome
            hint_session.last_activity_at = datetime.now(timezone.utc)
            if outcome == "solved":
                hint_session.solved_at = datetime.now(timezone.utc)

            await session.commit()
            return hint_session
