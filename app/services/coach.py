COACH_SYSTEM_PROMPT_TEMPLATE = """You are an expert competitive programmer and direct peer coach.

CRITICAL TONE CONSTRAINT:
You are strictly forbidden from using meta-announcements or artificial restriction phrases such as:
- "I cannot give you the solution directly"
- "As an AI coach, my role is to guide you"
- "I am only allowed to give you a nudge"
- "Let's take it step by step"
Do NOT explain what you are or aren't allowed to do. Speak directly about the problem, its mathematical invariants, constraints, counterexamples, and properties.

COACH OPERATING MODE: {coach_mode}
{mode_instruction}

LEVEL DEFINITION FOR LEVEL {target_level}:
{level_instruction}

GUARDRAILS:
- Do NOT provide full code solutions.
- At Level 0-3: Never use triple-backtick code fences.
- At Level 0-1: Never name specific algorithms or data structures.
- At Level 4: Mathematical pseudocode only. Never write syntax in C++, Python, or Java.
"""

MODE_INSTRUCTIONS = {
    "full_coach": (
        "Operating in FULL COACH mode. You have authoritative, verified editorial knowledge. "
        "Direct the student with confidence towards the verified invariant and approach."
    ),
    "cautious_coach": (
        "Operating in CAUTIOUS COACH mode. The editorial knowledge is unverified. "
        "Guide the student thoughtfully. Cross-check constraints and encourage invariant verification."
    ),
    "peer_mode": (
        "Operating in PEER MODE. No authoritative editorial is available. "
        "Collaborate as an equal peer brainstorming ideas, analyzing constraints, and testing edge cases."
    ),
}

LEVEL_INSTRUCTIONS = {
    0: (
        "Level 0 (Clarification / Diagnostic):\n"
        "Ask a sharp diagnostic question about the problem statement, time/memory constraints, "
        "or a small edge-case counterexample. Do NOT reveal any algorithms or properties."
    ),
    1: (
        "Level 1 (Socratic Nudge):\n"
        "Guide the student toward the key structural property, monotonic invariant, or symmetry of the problem. "
        "Do NOT name algorithms or data structures."
    ),
    2: (
        "Level 2 (Algorithmic Direction):\n"
        "Point out the algorithmic paradigm or modeling technique (e.g. dynamic programming on prefixes, "
        "bipartite graph modeling, binary search on answer, greedy sorting). Explain how the sub-problem decomposes."
    ),
    3: (
        "Level 3 (Concrete Strategy):\n"
        "Specify the exact state definition, transition relation, or data structure invariants. "
        "Detail how the optimal substructure or update mechanism works mathematically."
    ),
    4: (
        "Level 4 (Mathematical Pseudocode):\n"
        "Provide high-level mathematical steps for the algorithm. "
        "Use mathematical notation (sum, max, min, transitions) and natural language steps. "
        "STRICTLY NO programming language code or syntax (no C++, Python, Java)."
    ),
}


async def generate_hint(
    llm_client: LLMClient,
    target_level: int,
    coach_mode: str,
    problem: Problem,
    knowledge: Optional[ProblemKnowledge],
    dialog_history: List[Dict[str, str]],
    user_message: str,
    current_code: Optional[str] = None,
    fsm_evaluation: Optional[Dict[str, Any]] = None,
    is_hold: bool = False,
    session_id: Optional[int] = None,
) -> Tuple[str, bool]:
    """
    Generates hint via LLM, applies Tier 1 hard gate, regenerates if blocked,
    and returns (hint_text, tier1_blocked).
    """
    mode_inst = MODE_INSTRUCTIONS.get(coach_mode, MODE_INSTRUCTIONS["peer_mode"])
    lvl_inst = LEVEL_INSTRUCTIONS.get(target_level, LEVEL_INSTRUCTIONS[0])

    system_prompt = COACH_SYSTEM_PROMPT_TEMPLATE.format(
        coach_mode=coach_mode,
        mode_instruction=mode_inst,
        target_level=target_level,
        level_instruction=lvl_inst,
    )

    # Problem & knowledge context
    prob_context = f"Problem: {problem.title} (Rating: {problem.rating or 'Unrated'}, Tags: {problem.tags or []})\n"
    if knowledge:
        prob_context += f"Approach Summary: {knowledge.approach_summary or 'N/A'}\n"
        prob_context += f"Key Insight: {knowledge.key_insight or 'N/A'}\n"
        prob_context += f"Techniques: {knowledge.techniques or []}\n"
        prob_context += f"Common Pitfalls: {knowledge.common_pitfalls or []}\n"

    # Dialog context
    history_str = ""
    if dialog_history:
        turns = [f"{m['role'].upper()}: {m['content']}" for m in dialog_history[-4:]]
        history_str = "\nPrevious Turns:\n" + "\n".join(turns)

    # Code context
    code_str = ""
    if current_code:
        code_str = (
            f"\nStudent Code State:\n```\n{current_code}\n```\n"
            f"Analyze the student's code relative to Level {target_level}. "
            f"If there is a flaw, edge-case omission, or complexity bottleneck, guide them towards it with an invariant question. "
            f"DO NOT write code fixes."
        )

    hold_str = ""
    if is_hold:
        hold_str = (
            "\nNote: The student missed or struggled with the prior point. "
            "Hold at this level: provide a smaller counterexample or simpler diagnostic question without moving ahead."
        )

    eval_reason = f"\nEvaluator Note: {fsm_evaluation.get('reasoning', '')}" if fsm_evaluation else ""

    user_prompt = (
        f"{prob_context}\n"
        f"{history_str}\n"
        f"Student Message: {user_message}\n"
        f"{code_str}\n"
        f"{hold_str}\n"
        f"{eval_reason}\n\n"
        f"Provide your Level {target_level} coaching response following all constraints."
    )

    # 1. Primary generation
    resp = await llm_client.generate(
        system_prompt=system_prompt,
        user_prompt=user_prompt,
        temperature=0.2,
        caller="hint_generator",
        session_id=session_id,
    )
    hint_text = resp.content.strip()

    knowledge_techniques = knowledge.techniques if knowledge else []
    passed, violation = evaluate_tier1_guardrails(hint_text, target_level, knowledge_techniques)
    tier1_blocked = False

    # 2. Guardrail regeneration if violated
    if not passed:
        tier1_blocked = True
        logger.warning(f"Tier 1 guardrail blocked hint (Level {target_level}): {violation}")

        remediation_prompt = (
            f"{user_prompt}\n\n"
            f"CRITICAL: Your previous response was BLOCKED because: {violation}.\n"
            f"Regenerate your Level {target_level} response strictly adhering to all rules. "
            f"Do not include forbidden patterns or keywords."
        )

        resp2 = await llm_client.generate(
            system_prompt=system_prompt,
            user_prompt=remediation_prompt,
            temperature=0.0,
            caller="hint_generator",
            session_id=session_id,
        )
        hint_text = resp2.content.strip()

        passed2, violation2 = evaluate_tier1_guardrails(hint_text, target_level, knowledge_techniques)
        if not passed2:
            # Fallback safe response if regeneration still violated
            if target_level == 0:
                hint_text = "What is the maximum bound on the input variables, and what time complexity would pass within the 1-second limit?"
            elif target_level == 1:
                hint_text = "Consider what invariant remains preserved when examining the sequence in order. Can you identify an optimal substructure?"
            elif target_level == 2:
                hint_text = "Think about modeling this as a decision problem. What standard algorithmic paradigm decomposes these sub-problems?"
            elif target_level == 3:
                hint_text = "Define the mathematical state function S(i) representing the optimal value considering the first i elements. What is the recurrence?"
            else:
                hint_text = "Step 1: Compute prefix invariants. Step 2: For each query, evaluate boundary conditions mathematically."

    return hint_text, tier1_blocked


